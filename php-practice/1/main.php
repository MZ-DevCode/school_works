<?php // Открывающий тег PHP: говорит серверу, что внутри пойдет программный код PHP, а не HTML

// $db — имя переменной (в PHP все переменные начинаются с символа $).
// Мы создаем её, чтобы сохранить в ней готовое подключение к базе данных.
// = — оператор присваивания (записывает значение справа в переменную слева).
// new — ключевое слово, которое создает новый объект на основе какого-то класса.
// PDO (PHP Data Objects) — встроенный класс PHP для универсальной работы с базами данных.
// 'sqlite:shop.db' — строка параметров: указываем драйвер (sqlite) и файл базы данных (shop.db).
// Если файла shop.db нет на диске, SQLite автоматически создаст его в папке проекта.
$db = new PDO('sqlite:shop.db');

// $db — обращаемся к нашему созданному объекту подключения к базе данных.
// -> — оператор доступа к объектам (стрелочка): говорит PHP "взять объект слева и вызвать у него функцию справа".
// exec() — встроенный метод объекта PDO, который выполняет SQL-запрос, не ожидая ответа в виде данных (идеально для создания таблиц).
// Внутри кавычек передается сам SQL-запрос:
// CREATE TABLE IF NOT EXISTS products (...) — создать таблицу с именем products, если она ещё не существует.
// id INTEGER PRIMARY KEY AUTOINCREMENT — колонка id: целое число (INTEGER), 
// главный уникальный ключ строки (PRIMARY KEY), который сам увеличивается на 1 при добавлении новой записи (AUTOINCREMENT).
// title TEXT — колонка для текста (название товара).
// price INTEGER — колонка для целых чисел (цена товара).
$db->exec("CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT,
    price INTEGER
)");

// if — условный оператор ("если то, что внутри круглых скобок верно, выполняй код в фигурных скобках").
// ! — логическое "НЕ" (инвертирует значение: true меняет на false и наоборот).
// empty() — встроенная функция PHP, которая проверяет, пустая ли переменная (если поле пустое, вернет true).
// С помощью знака ! мы делаем наоборот: проверяем, что поле НЕ пустое.
// $_POST — суперглобальный ассоциативный массив PHP, в котором автоматически хранятся данные из отправленной HTML-формы (метод POST).
// ['title'] и ['price'] — ключи массива, соответствующие именам полей ввода (<input name="title">).
// && — логическое "И": условие сработает, только если И первое поле заполнено, И второе поле заполнено.
if(!empty($_POST['title']) && !empty($_POST['price'])){
    
    // $stmt — переменная (сокращение от statement — выражение / подготовленный запрос).
    // $db->prepare() — метод объекта базы данных, который отправляет SQL-запрос на подготовку.
    // Это главная защита от взломов (SQL-инъекций): база заранее знает структуру запроса.
    // INSERT INTO products (title, price) VALUES (?, ?) — SQL-команда вставки данных.
    // Знаки вопросов (?) — это плейсхолдеры (безопасные "пустые места"), куда позже подставятся данные от пользователя.
    $stmt = $db->prepare("INSERT INTO products (title, price) VALUES (?, ?)");
    
    // $stmt — обращаемся к нашему объекту подготовленного запроса.
    // ->execute() — метод, который окончательно выполняет запрос в базе данных.
    // [...] — синтаксис создания массива в PHP. Мы передаем туда данные из формы:
    // первый элемент ($_POST['title']) безопасно встанет вместо первого знака ?, второй — вместо второго.
    $stmt->execute([$_POST['title'], $_POST['price']]);
}

?> <!-- Закрывающий тег PHP -->
